package manifest

import (
	"errors"
	"fmt"
	"io"

	"github.com/BurntSushi/toml"
)

const (
	// Filename is the name of the manifest written by govendor.
	Filename       = "govendor.toml"
	SchemaVersion  = 4
	manifestHeader = "# Generated by govendor. DO NOT EDIT.\n\n"
)

// File represents a govendor.toml file.
type File struct {
	Schema    int                 `toml:"schema"`
	Workspace *Workspace          `toml:"workspace,omitempty"`
	Tool      Tools               `toml:"tool,omitempty"`
	Exclude   map[string][]string `toml:"exclude,omitempty"`
	Mod       map[string]Module   `toml:"mod"`
}

// New builds a File from resolved dependencies. Pass a non-nil workspace
// for workspace (go.work) projects, and a non-nil tool for modules with tool
// directives.
func New(deps []Module, workspace *Workspace, tool Tools, excludes map[string][]string) *File {
	mods := make(map[string]Module, len(deps))
	for _, m := range deps {
		mods[m.Path] = m
	}

	return &File{
		Schema:    SchemaVersion,
		Workspace: workspace,
		Tool:      tool,
		Exclude:   excludes,
		Mod:       mods,
	}
}

// Parse unmarshals a govendor.toml file into a File. The Path field of
// each Module is backfilled from its map key, since it is excluded from
// TOML encoding.
func Parse(data []byte) (*File, error) {
	var m File
	if err := toml.Unmarshal(data, &m); err != nil {
		return nil, err
	}
	if err := validateManifest(&m); err != nil {
		return nil, err
	}
	for path, cfg := range m.Mod {
		cfg.Path = path
		m.Mod[path] = cfg
	}
	return &m, nil
}

func validateManifest(m *File) error {
	if m.Schema == 0 {
		return errors.New("govendor.toml: missing required 'schema' field")
	}
	if m.Mod == nil {
		return errors.New("govendor.toml: missing required '[mod]' section")
	}
	if m.Workspace != nil {
		if m.Workspace.Go == "" {
			return errors.New("govendor.toml: [workspace] missing required 'go' field")
		}
		if len(m.Workspace.Modules) == 0 {
			return errors.New("govendor.toml: [workspace] missing required 'modules' field")
		}
	}
	for pkg, cfg := range m.Tool {
		if cfg.Version == "" {
			return fmt.Errorf("govendor.toml: [tool.%q] missing required 'version' field", pkg)
		}
	}
	return nil
}

// WriteTo encodes the manifest as TOML into w.
func (m *File) WriteTo(w io.Writer) (int64, error) {
	cw := &countingWriter{w: w}

	if _, err := io.WriteString(cw, manifestHeader); err != nil {
		return cw.n, err
	}

	if err := toml.NewEncoder(cw).Encode(m); err != nil {
		return cw.n, err
	}

	return cw.n, nil
}

type countingWriter struct {
	w io.Writer
	n int64
}

func (c *countingWriter) Write(p []byte) (int, error) {
	n, err := c.w.Write(p)
	c.n += int64(n)
	return n, err
}
