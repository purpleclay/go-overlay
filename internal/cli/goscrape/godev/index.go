package godev

import (
	"bytes"
	"errors"
	"fmt"
	"go/version"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"text/template"
)

const goIndexTemplate = `# Auto-generated by goscrape - do not edit manually
{
{{- range . }}
  "{{ .Version }}" = {date = "{{ .Date }}";};
{{- end }}
}
`

var indexTemplate = template.Must(template.New("go-index").Parse(goIndexTemplate))

// topLevelDateRe matches the top-level `date = "...";` field of a Go manifest.
var topLevelDateRe = regexp.MustCompile(`(?m)^  date = "([^"]*)";$`)

type goIndexEntry struct {
	Version string
	Date    string
}

// writeIndex regenerates dir/index.nix from every Go manifest in dir, newest
// version first. Ordering uses go/version rather than semver: Go release
// names such as 1.21rc2 and 1.17beta1 aren't valid semver.
func writeIndex(dir string) error {
	index, err := readIndexEntries(dir, nil)
	if err != nil {
		return err
	}

	slices.SortFunc(index, func(a, b goIndexEntry) int {
		return version.Compare("go"+b.Version, "go"+a.Version)
	})

	var buf bytes.Buffer
	if err := indexTemplate.Execute(&buf, index); err != nil {
		return fmt.Errorf("failed to generate index: %w", err)
	}

	return os.WriteFile(filepath.Join(dir, "index.nix"), buf.Bytes(), 0o644)
}

// readIndexEntries reads the version and date of every Go manifest in dir.
// Every other .nix file is rejected rather than skipped: lib/manifests.nix
// loads each one as a Go version, so a stray file would break the overlay
// anyway. A directory that doesn't exist yet has no entries.
//
// Every .nix entry, index.nix included, must be a regular file, matching
// what lib/manifests.nix loads. Writing a manifest or the index follows a
// symlink, so accepting one could overwrite a file outside dir.
//
// Files named in replacing are otherwise skipped: they're about to be
// overwritten, so a malformed copy on disk mustn't stop the run that would
// repair it.
func readIndexEntries(dir string, replacing map[string]bool) ([]goIndexEntry, error) {
	entries, err := os.ReadDir(dir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("failed to read manifest directory: %w", err)
	}

	var index []goIndexEntry
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".nix") {
			continue
		}
		if !e.Type().IsRegular() {
			return nil, fmt.Errorf("manifest %s is not a regular file", name)
		}
		if name == "index.nix" || replacing[name] {
			continue
		}

		ver := strings.TrimSuffix(name, ".nix")
		if !version.IsValid("go" + ver) {
			return nil, fmt.Errorf("manifest %s is not named after a Go version", name)
		}

		content, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return nil, fmt.Errorf("failed to read manifest %s: %w", name, err)
		}

		dateMatch := topLevelDateRe.FindStringSubmatch(string(content))
		if dateMatch == nil {
			return nil, fmt.Errorf("manifest %s has no top-level date", name)
		}

		index = append(index, goIndexEntry{Version: ver, Date: dateMatch[1]})
	}
	return index, nil
}
